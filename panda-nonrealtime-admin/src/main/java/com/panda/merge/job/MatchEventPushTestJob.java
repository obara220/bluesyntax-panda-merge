    @Override
    public ReturnT<String> execute(String matchIds) throws Exception {
        //log.info("MatchEventCommonCleanJob param:{}",matchIds);
        if(StringUtils.isNotEmpty(matchIds)){
            matchSourceIds = matchIds;
        }
        if(matchStandardThirdIds.entrySet().size()==0){
            String [] arr = matchSourceIds.split(",");
            for (String s : arr) {
                ThirdMatchInfoExample thirdMatchInfoExample =new ThirdMatchInfoExample();
                thirdMatchInfoExample.createCriteria().andDataSourceCodeEqualTo(dataSourceCode)
                        .andThirdMatchSourceIdEqualTo(s);
                List<ThirdMatchInfo> list = thirdMatchInfoMapper.selectByExample(thirdMatchInfoExample) ;
                if(list.size()!=0){
                    if(list.get(0).getReferenceId()!=null){
                        matchStandardThirdIds.put(list.get(0).getReferenceId(),list.get(0).getId());
                    }
                }
            }
            for (Map.Entry<Long, Long> longLongEntry : matchStandardThirdIds.entrySet()) {
                IDLIST.add(longLongEntry.getKey()+","+longLongEntry.getValue());
            }
        }

        List<String> originalList = IDLIST;
        int partitionsize = 47;
        List<List<String>> partitionedList = IntStream.range(0, originalList.size()).boxed().
                collect(Collectors.groupingBy(index -> index / partitionsize)).values().stream().
                map(indices -> indices.stream().map(originalList::get).collect(Collectors.toList())).collect(Collectors.toList());

        for (List<String> list : partitionedList) {
            this.sendEvent(list);
            this.sendEvent(list);
        }
        return ReturnT.SUCCESS;
    }


