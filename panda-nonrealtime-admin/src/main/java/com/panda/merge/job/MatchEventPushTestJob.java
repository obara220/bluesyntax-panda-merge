    @Async("EventInfoTestPool")
    public void sendEvent(List<String> arr) {
        for (String s : arr) {
            String[] xx =s.split(",");
            MatchEventInfo eventInfo = JSON.parseObject(String.valueOf(eventOldInfo), MatchEventInfo.class);
            Long standardMatchId = Long.parseLong(xx[0]);
            Long thirdMatchId =  Long.parseLong(xx[1]);
            String eventCode = this.randomEventCode();
            eventInfo.setThirdMatchId(thirdMatchId);
            eventInfo.setStandardMatchId(standardMatchId);
            eventInfo.setDataSourceCode(dataSourceCode);
            eventInfo.setEventCode(eventCode);
            eventInfo.setLinkId(UUID.randomUUID().toString());
            List<MatchEventInfo> list =new ArrayList<>();
            list.add(eventInfo);
            Request<List<MatchEventInfo>> reqMessage = new Request<>();
            reqMessage.setLinkId(eventInfo.getLinkId());
            reqMessage.setData(list);
            MessageBuilder<Request<List<MatchEventInfo>>> builder = MessageBuilder.withPayload(reqMessage)
                    .setHeader(MessageConst.PROPERTY_KEYS, reqMessage.getLinkId());
            rocketMqTemplate.send("MATCH_EVENT_INFO_TO_RISK:" + eventInfo.getThirdMatchId(), builder.build());
            //log.info("::{}::开始组装压测比分事件下发,topic:MATCH_EVENT_INFO_TO_RISK,request={}", reqMessage.getLinkId(), JSON.toJSONString(reqMessage));
        }

    }

    @Bean("EventInfoTestPool")
    public TaskExecutor getEventInfoThreadPool() {
        ThreadPoolTaskExecutor executor = new VisiableThreadPoolTaskExecutor();
        //配置核心线程数
        executor.setCorePoolSize(128);
        //配置最大线程数
        executor.setMaxPoolSize(256);
        //配置队列大小
        executor.setQueueCapacity(512);
        // 设置线程活跃时间（秒）
        //executor.setKeepAliveSeconds(60);
        //配置线程池中的线程的名称前缀
        executor.setThreadNamePrefix("ThreadPool-access-eventInfo-data-");
        //当任务数量超过MaxPoolSize和QueueCapacity时使用的策略，该策略指不在新线程中执行任务，而是有调用者所在的线程来执行
        executor.setRejectedExecutionHandler(new ThreadPoolExecutor.CallerRunsPolicy());
        // 等待所有任务结束后再关闭线程池
        executor.setWaitForTasksToCompleteOnShutdown(true);
        //线程池初始化
        executor.initialize();
        return executor;
    }

